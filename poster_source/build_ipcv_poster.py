def main() -> None:
    prs = Presentation()
    prs.slide_width, prs.slide_height = W, H
    slide = prs.slides.add_slide(prs.slide_layouts[6])

    rect(slide, 0, 0, W, H, PAPER)
    build_header(slide)
    build_col1(slide)
    build_col2(slide)
    build_col3(slide)
    build_footer(slide)

    ends = []
    for i in range(3):
        lo = COL_X[i] - Inches(0.02)
        hi = COL_X[i] + COL_W + Inches(0.02)
        vals = []
        for sh in slide.shapes:
            if (sh.width or 0) >= W - Inches(0.5):      # full-width bands and rules
                continue
            if not lo <= (sh.left or 0) <= hi:
                continue
            if (sh.top or 0) < BODY_TOP - Inches(0.05):
                continue
            if (sh.top or 0) >= H - FOOTER_H:            # footer band
                continue
            vals.append((sh.top or 0) + (sh.height or 0))
        ends.append(max(vals) / 914400)

    prs.save(OUT)
    print(f"wrote {OUT.relative_to(ROOT)}  ({W.inches:.3f} × {H.inches:.3f} in = "
          f"{W.inches * 25.4:.0f} × {H.inches * 25.4:.0f} mm, {len(slide.shapes)} shapes)")
    for i, e in enumerate(ends, 1):
        flag = "  OVER" if e > BODY_BOTTOM / 914400 else ""
        print(f"  column {i} ends at {e:.2f} in (limit {BODY_BOTTOM / 914400:.2f}){flag}")


if __name__ == "__main__":
    main()

# ----------------------------------------------------------- text helpers ----
_FONTS: dict[tuple[int, bool], ImageFont.FreeTypeFont] = {}


def _font(size_pt: float, bold: bool) -> ImageFont.FreeTypeFont:
    key = (int(round(size_pt * 4)), bold)
    if key not in _FONTS:
        path = Path("C:/Windows/Fonts/segoeuib.ttf" if bold else "C:/Windows/Fonts/segoeui.ttf")
        _FONTS[key] = ImageFont.truetype(str(path), key[0])
    return _FONTS[key]


def _width_pt(text: str, size: float, bold: bool) -> float:
    return _font(size, bold).getlength(text) / 4.0 if text else 0.0


def _wrap(runs, width_pt: float, size: float, bullet_pt: float = 0.0) -> int:
    words: list[tuple[str, bool]] = []
    for text, bold in runs:
        parts = text.split(" ")
        for i, piece in enumerate(parts):
            if piece:
                words.append((piece + (" " if i < len(parts) - 1 else ""), bold))
    lines, current, limit = 1, bullet_pt, width_pt
    for word, bold in words:
        w = _width_pt(word, size, bold)
        if current + w > limit and current > 0:
            lines += 1
            current, limit = w, width_pt
        else:
            current += w
    return lines


def _height(runs_list, width_in: float, size: float, space_after: float,
            bullet: bool = False) -> Emu:
    total = 0.0
    for runs in runs_list:
        indent = size * 0.55 if bullet else 0.0
        lines = _wrap(runs, width_in * 72 - indent, size, indent)
        total += lines * size * 1.33 + space_after
    return Emu(int(total * 12700))


# ------------------------------------------------------------ shape helpers --
def rect(slide, x, y, w, h, fill=None, line=None, shape=MSO_SHAPE.RECTANGLE, lw=0.75):
    sh = slide.shapes.add_shape(shape, int(x), int(y), int(w), int(h))
    sh.shadow.inherit = False
    if fill is None:
        sh.fill.background()
    else:
        sh.fill.solid()
        sh.fill.fore_color.rgb = fill
    if line is None:
        sh.line.fill.background()
    else:
        sh.line.color.rgb = line
        sh.line.width = Pt(lw)
    sh.text_frame.word_wrap = True
    return sh


def textbox(slide, x, y, w, h):
    tb = slide.shapes.add_textbox(int(x), int(y), int(w), int(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = MSO_ANCHOR.TOP
    return tb


def para(tf, runs, size, colour=INK_SOFT, bold=False, first=False, align=PP_ALIGN.LEFT,
         space_after=0, line=1.0, bullet=False):
    p = tf.paragraphs[0] if first else tf.add_paragraph()
    p.alignment = align
    p.line_spacing = line
    p.space_after = Pt(space_after)
    p.space_before = Pt(0)
    if bullet:
        p.text = ""
        r0 = p.add_run()
        r0.text = "•  "
        r0.font.size = Pt(size)
        r0.font.bold = True
        r0.font.name = FONT
        r0.font.color.rgb = LEAF
        p.level = 0
    pairs = [(runs, bold)] if isinstance(runs, str) else runs
    for txt, is_bold in pairs:
        r = p.add_run()
        r.text = txt
        r.font.size = Pt(size)
        r.font.bold = is_bold
        r.font.name = FONT
        r.font.color.rgb = colour
    return p


def section(slide, x, y, w, num, title, size=14.5):
    """Numbered section header: badge + title + rule. Returns bottom y."""
    b = Inches(0.26)
    badge = rect(slide, x, y, b, b, LEAF, shape=MSO_SHAPE.ROUNDED_RECTANGLE)
    badge.adjustments[0] = 0.18
    tf = badge.text_frame
    tf.margin_left = tf.margin_right = 0
    tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    para(tf, str(num), 10.5, PAPER, bold=True, first=True, align=PP_ALIGN.CENTER)
    tf2 = textbox(slide, x + b + Inches(0.11), y - Inches(0.03), w - b - Inches(0.11), Inches(0.32)).text_frame
    para(tf2, title, size, NAVY, bold=True, first=True)
    rule = rect(slide, x, y + b + Inches(0.08), w, Emu(12700), RULE)
    rule.line.fill.background()
    return y + b + Inches(0.11)


def body_text(slide, x, y, w_in, items, size=10, space_after=3.5, bullet=False,
              colour=INK_SOFT, line=0.98):
    norm = [([(i, False)] if isinstance(i, str) else i) for i in items]
    h = _height(norm, w_in, size, space_after, bullet)
    tf = textbox(slide, x, y, Inches(w_in), h).text_frame
    for i, runs in enumerate(norm):
        para(tf, runs, size, colour, first=(i == 0), bullet=bullet,
             space_after=space_after, line=line)
    return y + h


def caption(slide, x, y, w_in, text, size=8.5):
    h = _height([[(text, False)]], w_in, size, 0)
    tf = textbox(slide, x, y, Inches(w_in), h).text_frame
    para(tf, text, size, GREY, first=True, line=0.98)
    return y + h


def fit_picture(slide, path, x, y, max_w, max_h):
    iw, ih = Image.open(path).size
    scale = min(max_w / iw, max_h / ih)
    w, h = int(iw * scale), int(ih * scale)
    px = int(x + (max_w - w) / 2)
    slide.shapes.add_picture(str(path), px, int(y), w, h)
    return y + h


def chip(slide, x, y, w, h, label, size=9.5, fill=LEAF_PALE, edge=LEAF_LT, colour=INK):
    sh = rect(slide, x, y, w, h, fill, line=edge, shape=MSO_SHAPE.ROUNDED_RECTANGLE)
    sh.adjustments[0] = 0.16
    tf = sh.text_frame
    tf.margin_left = Inches(0.09)
    tf.margin_right = Inches(0.06)
    tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    para(tf, label, size, colour, first=True, line=0.94)


def table(slide, x, y, w, rows, col_in, size=9.5, row_h=Inches(0.27), center_cols=(1,)):
    nrows, ncols = len(rows), len(rows[0])
    gf = slide.shapes.add_table(nrows, ncols, int(x), int(y), int(w),
                                int(row_h * nrows))
    tbl = gf.table
    tbl.first_row = True
    tbl.horz_banding = False
    for j, cw in enumerate(col_in):
        tbl.columns[j].width = Inches(cw)
    for i, row in enumerate(rows):
        tbl.rows[i].height = int(row_h)
        for j, val in enumerate(row):
            cell = tbl.cell(i, j)
            cell.margin_left = Inches(0.06)
            cell.margin_right = Inches(0.04)
            cell.margin_top = cell.margin_bottom = 0
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.fill.solid()
            if i == 0:
                cell.fill.fore_color.rgb = NAVY
            else:
                cell.fill.fore_color.rgb = PAPER if i % 2 else LEAF_PALE
            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            p.alignment = PP_ALIGN.CENTER if j in center_cols else PP_ALIGN.LEFT
            r = p.add_run()
            r.text = str(val)
            r.font.size = Pt(size)
            r.font.bold = (i == 0)
            r.font.name = FONT
            r.font.color.rgb = PAPER if i == 0 else INK
    return y + row_h * nrows



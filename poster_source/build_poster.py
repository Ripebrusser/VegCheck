def main() -> None:
    prs = Presentation()
    prs.slide_width, prs.slide_height = W, H
    slide = prs.slides.add_slide(prs.slide_layouts[6])

    add_shape(slide, 0, 0, W, H, PAPER)
    build_header(slide)
    build_column1(slide)
    y2 = build_column2(slide)
    build_column2_tail(slide, y2)
    build_column3(slide)
    build_web_and_refs(slide)

    over = []
    for sh in slide.shapes:
        top = sh.top or 0
        bottom = top + (sh.height or 0)
        # Body content (starts above the references band) must finish before it.
        if BODY_TOP < top < REFS_TOP - Inches(0.02) and bottom > REFS_TOP:
            over.append((str(sh.shape_type), round(top / 914400, 2),
                         round(bottom / 914400, 2)))

    prs.save(OUT)
    print(f"wrote {OUT.relative_to(ROOT)}  ({W.inches:.2f} × {H.inches:.2f} in = "
          f"{W.inches * 25.4:.0f} × {H.inches * 25.4:.0f} mm, {len(slide.shapes)} shapes)")
    print(f"shapes crossing the references band: {len(over)}")
    for o in over:
        print("   ", o)


if __name__ == "__main__":
    main()

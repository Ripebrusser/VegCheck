# ------------------------------------------------------- text measurement ----
_FONT_CACHE: dict[tuple[int, bool], ImageFont.FreeTypeFont] = {}


def _font(size_pt: float, bold: bool) -> ImageFont.FreeTypeFont:
    key = (int(round(size_pt * 4)), bold)
    if key not in _FONT_CACHE:
        path = Path("C:/Windows/Fonts/segoeuib.ttf" if bold else "C:/Windows/Fonts/segoeui.ttf")
        _FONT_CACHE[key] = ImageFont.truetype(str(path), key[0])
    return _FONT_CACHE[key]


def _text_pt(text: str, size: float, bold: bool) -> float:
    """Width of a run in points (measured at 4× and scaled back)."""
    if not text:
        return 0.0
    return _font(size, bold).getlength(text) / 4.0


def _wrap(runs, width_pt: float, size: float) -> int:
    """Greedy word wrap across mixed bold/regular runs; returns line count."""
    words: list[tuple[str, bool]] = []
    for text, bold in runs:
        for i, piece in enumerate(text.split(" ")):
            if piece == "":
                continue
            words.append((piece + (" " if i < len(text.split(" ")) - 1 else ""), bold))
    lines, current = 1, 0.0
    for word, bold in words:
        w = _text_pt(word, size, bold)
        if current + w > width_pt and current > 0:
            lines += 1
            current = w
        else:
            current += w
    return lines


def _para_height(runs, width_in: float, size: float, line_spacing: float,
                 space_after: float, bullet: str | None = None) -> float:
    """Height in points of one paragraph, including its trailing space."""
    width_pt = width_in * 72.0
    if bullet:
        width_pt -= _text_pt(bullet, size, True)
    # The hanging bullet indent narrows every line, so wrap against the usable width.
    lines = _wrap(runs, width_pt - 28, size)
    # Segoe UI's line height is ~1.33 em in PowerPoint; 1.2 underestimates it and
    # text then collides with the section below.
    return lines * size * 1.33 * line_spacing + space_after


# ---------------------------------------------------------------- helpers ----
def add_shape(slide, x, y, w, h, fill, line=None, shape=MSO_SHAPE.RECTANGLE):
    s = slide.shapes.add_shape(shape, int(x), int(y), int(w), int(h))
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(1.2)
    s.shadow.inherit = False
    return s


def textbox(slide, x, y, w, h, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(int(x), int(y), int(w), int(h))
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = 0
    tf.margin_top = tf.margin_bottom = 0
    return box


def para(tf, runs, size=21, colour=INK_SOFT, first=False, bullet=None,
         space_after=6, line=0.98, align=PP_ALIGN.LEFT):
    p = tf.paragraphs[0] if first else tf.add_paragraph()
    p.alignment = align
    p.line_spacing = line
    p.space_after = Pt(space_after)
    p.space_before = Pt(0)
    if bullet:
        r = p.add_run()
        r.text = bullet
        r.font.size = Pt(size)
        r.font.bold = True
        r.font.color.rgb = EMERALD
        r.font.name = FONT
    if isinstance(runs, str):
        runs = [(runs, False)]
    for text, bold in runs:
        r = p.add_run()
        r.text = text
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.color.rgb = colour
        r.font.name = FONT
    return p


def block(slide, x, y, w_in, items, size=20, colour=INK_SOFT, bullet="▪  ",
          space_after=9, line=0.98):
    """Draw a bulleted block sized from measured text. Returns the bottom y."""
    normalised = [([(i, False)] if isinstance(i, str) else i) for i in items]
    total_pt = sum(_para_height(runs, w_in, size, line, space_after, bullet)
                   for runs in normalised)
    height = Emu(int(total_pt * 12700))
    box = textbox(slide, x, y, Inches(w_in), height)
    tf = box.text_frame
    for i, runs in enumerate(normalised):
        para(tf, runs, size=size, colour=colour, first=(i == 0), bullet=bullet,
             space_after=space_after, line=line)
    return y + height


def prose(slide, x, y, w_in, paragraphs, size=18, colour=INK_SOFT, line=1.0,
          space_after=8, colour_by_index=None):
    total_pt = sum(_para_height(p, w_in, size, line, space_after) for p in paragraphs)
    height = Emu(int(total_pt * 12700))
    tf = textbox(slide, x, y, Inches(w_in), height).text_frame
    for i, runs in enumerate(paragraphs):
        para(tf, runs, size=size, colour=colour, first=(i == 0),
             space_after=space_after, line=line)
    return y + height


def section(slide, x, y, w, title, height=Inches(0.64), size=28):
    bar = add_shape(slide, x, y, w, height, EMERALD_DK)
    tf = bar.text_frame
    tf.word_wrap = True
    tf.margin_left = Inches(0.22)
    tf.margin_right = Inches(0.10)
    tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = title.upper()
    r.font.size = Pt(size)
    r.font.bold = True
    r.font.color.rgb = PAPER
    r.font.name = FONT
    return y + height


def picture(slide, path: Path, x, y, max_w, max_h):
    with Image.open(path) as im:
        iw, ih = im.size
    scale = min(max_w / iw, max_h / ih)
    w, h = int(iw * scale), int(ih * scale)
    left = int(x + (max_w - w) / 2)
    slide.shapes.add_picture(str(path), left, int(y), width=w, height=h)
    return y + h


def caption(slide, x, y, w_in, body, size=14.5, colour=GREY, italic=True):
    lines = _wrap([(body, False)], w_in * 72, size)
    height = Emu(int(lines * size * 1.33 * 0.96 * 12700))
    tf = textbox(slide, x, y, Inches(w_in), height).text_frame
    p = tf.paragraphs[0]
    p.line_spacing = 0.96
    r = p.add_run()
    r.text = body
    r.font.size = Pt(size)
    r.font.italic = italic
    r.font.color.rgb = colour
    r.font.name = FONT
    return y + height


def table(slide, x, y, w, rows, widths, size=16, row_h=Inches(0.5), header=True):
    n_rows, n_cols = len(rows), len(rows[0])
    shape = slide.shapes.add_table(n_rows, n_cols, int(x), int(y), int(w), int(row_h * n_rows))
    tbl = shape.table
    total = sum(widths)
    for j, cw in enumerate(widths):
        tbl.columns[j].width = Emu(int(w * cw / total))
    for i, row in enumerate(rows):
        tbl.rows[i].height = int(row_h)
        for j, val in enumerate(row):
            cell = tbl.cell(i, j)
            cell.margin_left = Inches(0.08)
            cell.margin_right = Inches(0.05)
            cell.margin_top = cell.margin_bottom = Inches(0.02)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.fill.solid()
            cell.fill.fore_color.rgb = EMERALD_DK if (i == 0 and header) else (
                PAPER if i % 2 else MINT)
            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            r = p.add_run()
            r.text = str(val)
            r.font.size = Pt(size)
            r.font.name = FONT
            r.font.bold = (i == 0 and header) or j == 0
            r.font.color.rgb = PAPER if (i == 0 and header) else INK
    return y + row_h * n_rows


def stat_row(slide, x, y, w, items, height=Inches(1.14), gap=Inches(0.14), size=26):
    n = len(items)
    cw = int((w - gap * (n - 1)) / n)
    for i, (value, label) in enumerate(items):
        cx = x + i * (cw + gap)
        add_shape(slide, cx, y, cw, height, MINT, line=OUTLINE)
        add_shape(slide, cx, y, cw, Pt(5), EMERALD)
        tf = textbox(slide, cx + Inches(0.13), y + Inches(0.14), cw - Inches(0.22),
                     Inches(0.5)).text_frame
        para(tf, value, size=size, colour=EMERALD_DK, first=True, space_after=0)
        tf2 = textbox(slide, cx + Inches(0.13), y + Inches(0.60), cw - Inches(0.22),
                      height - Inches(0.66)).text_frame
        para(tf2, label, size=13.5, colour=INK_SOFT, first=True, space_after=0, line=0.94)
    return y + height


